"""读网页（web_fetch）：给自己不能联网的模型（GPT、Gemini、DeepSeek、自定义接口）用的一个只读的小工具。

Claude 联网靠 Anthropic 服务器上的两个工具（联网搜索、读网页，见 tools/web.py），别家的模型没有。浏览器（browser/）
什么网页都能看，但要装 Chrome、要开设置、每一步都要和 Chrome 来回好几次。很多时候模型只是想读一下你给的那个网址：
这里就是做这件事的最小的一个工具。给它一个 http(s) 网址，它把网页下载下来，取出能读的文字交给模型。
不执行网页里的脚本，不带 Cookie，不发任何密钥。它不是搜索：模型得先知道网址。

几个文件：
  guard.py     哪些地址不能去：这台电脑、局域网、云服务器的"元数据"地址……（判断只看地址本身，和 DNS 无关）
  client.py    真的去取：自己解析域名、检查每一个地址、连到检查过的那个地址上，自己跟着跳转（每一跳都重新检查），
               有时间、大小、跳转次数的上限
  charset.py   字节 → 文字：按回答的头、BOM、网页里的 <meta charset> 认编码
  readable.py  HTML → 能读的文字：去掉脚本、样式、导航这些，留下标题、段落、列表、表格，链接少量写上网址
  content.py   按类型交给上面哪一个：网页、纯文本、JSON，Word / Excel / PowerPoint（documents.py）；PDF、图片不读
  session.py   每次运行（一段对话、一次定时任务、一个聊天）自己的一份：允许过哪些网站、这条消息里读了几次

安全的边界（这是一条硬规矩，没有开关；要看本机、局域网里的网页，用浏览器）：
  - 只认 http 和 https。网址里带用户名、密码的不读（会被当成认证发出去）。
  - 域名解析出来的每一个地址都要是公网的。这台电脑（127.0.0.0/8、::1）、局域网（10/8、172.16/12、192.168/16、fc00::/7）、
    链路本地（169.254/16、fe80::/10，云服务器的元数据 169.254.169.254 就在这里）、运营商级 NAT（100.64/10，
    阿里云的元数据 100.100.100.200 在这里）、组播、保留的、"未指定"的（0.0.0.0、::）一律不去。
    藏在 IPv6 里的 IPv4（::ffff:127.0.0.1、64:ff9b::/96、6to4 的 2002::/16）按里面那个 IPv4 判断。
  - 查过的地址就是连上去的地址（DNS 重绑定：第一次解析给公网地址、真正连的时候换成 127.0.0.1）。TLS 照样按域名验证证书。
  - 跳转自己跟，最多几次，每一跳都从头再查一遍（一个公网的网站可以把你跳到 http://169.254.169.254/）。
  - 不走代理：走代理的话，是代理去解析、去连，我们管不住它连到哪儿。

问不问你（写在 permissions.py，和浏览器"打开一个新的网站"挨着）：网址本身就能把东西带出去
（被网页里的一句话带偏的模型去读 evil.com/?data=你的邮件），所以这段对话里第一次读一个网站之前先问你，
卡片上写着完整的网址；允许过的网站这段对话里再读不问。"全部自动允许"不问；定时任务和聊天通道按它们自己的那一档。
"""
