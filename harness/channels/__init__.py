"""聊天通道：在 Telegram 这类聊天软件里和智狐说话，手机上也能用，在服务器上可以远程运维。

一个聊天通道是怎么工作的（以 Telegram 为例）：

    你的手机 ──消息──► Telegram 的服务器 ◄──长轮询（getUpdates）── 智狐（你的电脑或服务器）
                                                                    │
                       ┌────────────────────────────────────────────┘
                       ▼
    是主人吗（配对绑定过的账号）？ 不是：不理。是：这个聊天的会话里跑一轮 agent 循环（和网页上的一模一样）
                       │
                       ▼
    写完一段文字就发回聊天里；要执行命令、改文件时，发一条带"允许 / 拒绝"按钮的消息，等你点（网页上也能点）

几个要点：

  不需要公网地址。是智狐去问 Telegram"有没有我的消息"，Telegram 不用来找智狐。家里的电脑、公司内网里的
  服务器都能用，不用开端口、不用隧道。（WhatsApp、企业微信只会把消息推到一个公网网址，所以放到第二阶段。）

  只听主人一个人的。机器人的名字谁都能搜到，可它能在你的电脑上执行命令。所以要先配对：页面上显示一个
  6 位数字，你用自己的账号发给机器人，这个账号就记成主人，别人的消息一律不理（见 pairing.py）。

  要你批准的操作照样要你批准。每个通道有自己的一档"要不要先问你"（和对话里的三档一样，默认每次都问）。
  确认请求里写着完整的命令和工作目录，看清楚再点。

  和网页上的对话同时进行。每个聊天有自己的会话、助手和 shell：在聊天里发 /stop 只停这个聊天，
  网页上的"停止"也碰不到它（见 session.py）。花的钱照样记账，来源写着 channel。

这个文件夹里每个文件只讲一件事：

  base.py       一个平台要实现的几个方法（Channel），以及收发的东西长什么样
  platforms.py  有哪些平台、各自到了哪一步（页面上的卡片照着它画）
  pairing.py    配对的规则
  store.py      设置和记录（data/channels.json：token、主人、确认方式……）
  telegram.py   Telegram：手写的 Bot API 客户端
  markup.py     把模型写的 Markdown 排成聊天软件里的样子、拆成不超长的几段
  ui.py         聊天里的对话用的"界面"（agent 循环通过它说话）
  session.py    一个聊天：会话、助手、排队、跑一轮
  outbound.py   助手用 send_file 往聊天里发文件：这个平台收什么（plan），发到哪个聊天（Outlet）
  router.py     来了一条消息该交给谁；发送队列
  hub.py        哪些通道开着；网页和命令行上的操作
  cli.py        命令行：harness channels setup / pair / status / approval
"""
