"""撤回一轮改的文件：每一轮对话里文件工具改了哪些文件，点一下就恢复成这一轮之前的样子。

为什么要有它
------------
倒回对话（编辑最后一条消息、重新生成，见 rewind.py）倒回去的只是对话：已经改了的文件还是改了的。
这个功能是它的另一半：对话不动，把一轮改的文件恢复回去。两件事分开做，也可以一起做（倒回最后一轮时
确认卡片上可以勾"同时撤回这一轮改的文件"）。

怎么记下来（journal.py）
------------------------
一轮开始时，界面（网页的 WebApp._run_turn、终端的 cli.ask_turn）打开一本"这一轮的账"（Journal），
文件工具每次改文件之前问一句"有没有在记账"（journal.watching）：有的话，第一次碰到这个文件时先把它
改之前的样子留一份底（存在 data/backups/turns/<编号>/ 里），改完再记下改之后的样子。一轮结束时把账合上，
写一份清单（manifest.json），页面上这一轮的末尾多一行"改了 N 个文件"（一个 file_changes 事件）。

账记在"这一轮的线程"上（ContextVar）：你的对话、几个定时任务、聊天通道是同时跑的，各在各的线程里，
文件工具却只有一份（见 tools/files.py）。所以记下来的只是你这一轮（连同它交给子 Agent 做的，子 Agent 在同一个线程里跑）
改的文件；定时任务和聊天通道改的不记（它们自己跑的时候多半没人看着，撤回要在它们那段会话里做，以后再说）。

记下什么、不记什么
------------------
  记      文件工具（str_replace_based_edit_tool）的 create、str_replace、insert：新建、覆盖、修改。
  不记    执行命令（run_command）改的文件。一条命令能改什么我们看不到：sed -i、git checkout、npm install、
          一个脚本……要知道它改了什么，只能在每条命令前后把整个工作目录拍一遍，大的项目里又慢又占地方，
          而且命令还能改工作目录之外的东西。所以不假装能撤：页面上明说"命令改动的文件没法自动撤回"。
  不做    git 快照。工作目录是 git 仓库时，本来可以每一轮 git stash / 提交一次，连命令改的也能撤回。
          没有这样做，因为那是你的仓库：会在你的 stash 列表、提交记录里留下东西，和你正在做的 rebase、
          暂存区搅在一起；被 .gitignore 忽略的文件照样撤不回；还要每台电脑上都装着 git。
          用 git 的人自己提交一次，就是最可靠的"撤回点"；这里只管智狐自己能看清的那部分。

撤回和重做（restore.py）
------------------------
  撤回    每个文件恢复成这一轮之前的样子；这一轮新建的文件删掉（连同为它新建的空文件夹）。
          撤回之前先把文件现在的样子留一份底：重做就是把它放回去。
  重做    把撤回时换下来的那一份放回去。
  冲突    这一轮之后文件又被改过（后面的一轮、你自己、别的程序），撤回会把那些改动一起冲掉。
          靠内容的哈希认出来（不看修改时间：复制、解压都会改它），在原地说清楚，要你点"仍然撤回"才做。
          后面的几轮也改过同一个文件时另外说明：撤回的是"这一轮之前"的样子，后面那几轮对它的改动也会一起没了。
  不做    保存密钥、权限设置的那几个文件（和文件工具同一份名单，见 tools/files.py 的 protected），
          留底的文件夹本身，换成了符号链接的路径（撤回只写当初记下的那个位置，不跟着链接去别处），
          留底已经清理掉、对不上哈希、太大没留底的。
  多问    工作目录之外的文件、助手自己的数据目录里的文件：当初改它们就要你点头（见 permissions.py），
          撤回时也一样，先说清楚是哪儿，要你点"仍然撤回"。

撤回和重做只有你能做：网页上的按钮、终端里的 /undo。模型没有任何能撤回的工具。

撤回的记录（事件）
------------------
撤回、重做本身也是一个事件（file_undo），和别的事件一样存进会话文件、刷新时重放：页面上看得到什么时候撤回过，
"改了 N 个文件"那一行上每个文件现在是什么状态，都由这些事件推出来（restore.fold）。会话文件里的 messages 一个字都不动。
清单（manifest.json）写好以后不再改：它记的是"这一轮做了什么"；"后来撤回过没有"只记在事件里。
一件事只记在一处，两边才不会对不上。

撤回以后告诉模型（notes.py）
----------------------------
模型记得它改过的文件是什么样子。你撤回以后它还以为改动在，接下来要么 str_replace 找不到原文，
要么照着记忆把整个文件重写一遍，把撤回的又写了回去。所以下一条消息前面附一段说明：哪些文件撤回了、重做了，
用到之前先重新看一眼。附在消息里（和时间、Skill 目录一样），不改系统提示词、不改前面的历史。
倒回最后一轮时一起撤回的不用说：那一轮已经从历史里去掉了，模型本来就不知道它改过。
"""
